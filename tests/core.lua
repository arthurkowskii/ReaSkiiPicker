local root = assert(arg[1])
local M = dofile(root .. '/src/model.lua')
local count = 0
local function check(value, label)
  assert(value, label); count = count + 1; print('PASS\t' .. label)
end
local state = {categories={{id='fx', name='Effects', order=0}, {id='eq', name='EQ', parentId='fx', order=0}},
 plugins={{id='one', name='VST3: ReaEQ', ident='eq', categoryIds={'fx'}, subcategoryIds={'eq'}}}}
local catalog = {{name='VST3: ReaEQ', ident='eq'}, {name='VST3: Other', ident='other'},
 {name='CLAP: ReaEQ', ident='eq-clap'}, {name='VST3: 100% [FX]', ident='literal'}}
M.validate(state)
local before = #state.plugins
check(#M.results(state,catalog,'other','eq') == 1, 'search ignores curated category filter')
check(#state.plugins == before, 'search never imports catalog into collection')
check(#M.results(state,catalog,'ReaEQ','') == 2, 'formats remain distinct')
check(#M.results(state,catalog,'100% [','') == 1, 'search is literal, not Lua patterns')
check(#M.results(state,catalog,'reA compressor','') == 0, 'all search tokens must match')
check(#M.results(state,catalog,'','eq') == 1, 'subcategory retained')
check(#M.results(state,catalog,'','fx') == 1, 'parent includes descendants')
local p = M.assign(state,catalog[2],'eq')
check(#state.plugins == 2 and p.ident == 'other','explicit assignment adds curated entry')
M.assign(state,catalog[2],'eq')
check(#state.plugins == 2,'assignment idempotent')
M.unassign(state,p,'eq')
check(#M.results(state,catalog,'','eq') == 1,'unassign removes selected membership')
check(#M.results(state,catalog,'other','eq') == 1,'unassign never removes global catalog entry')
check(#M.results(state,catalog,'','') == 2,'unassigned curated entry remains in collection')
check(not pcall(M.assign,state,catalog[2],'missing'),'unknown category refused')
local category = M.add_category(state,'  Test  ','fx')
check(category.name == 'Test' and category.parentId == 'fx','new child category normalized')
check(not pcall(M.add_category,state,'  ',''),'empty category refused')
check(not pcall(M.validate,{categories={{id='x',name='x',parentId='x'}},plugins={}}),'category cycles refused')
check(not pcall(M.validate,{categories={{id='x',name='x'},{id='x',name='x'}},plugins={}}),'duplicate category ids refused')
check(not pcall(M.validate,{categories={},plugins={{id='p',name='x',ident='x',categoryIds={'unknown'}}}}),'dangling memberships refused')
check(M.view_mode('volume',false,false)=='list','global search uses list presentation')
check(M.view_mode('',true,false)=='list','All FX uses list presentation')
check(M.view_mode('   ',false,false)=='grid','manual collection retains screenshot grid')
check(M.view_mode('',false,true)=='add','Add Plugin is a distinct non-inserting workflow')
check(#M.children(state,'')==1 and M.children(state,'')[1].id=='fx','only root folders appear in category bar')
check(M.children(state,'fx')[1].id=='eq','child folders belong to parent dropdown')
check(M.category_path(state,'eq')=='Effects / EQ','breadcrumb resolves nested folder names')
local remembered=M.remember(state,catalog[3])
check(remembered.ident=='eq-clap' and #(remembered.categoryIds or {})==0,'Add Plugin can save an unclassified entry')
local n=#state.plugins; M.remember(state,catalog[3])
check(#state.plugins==n,'Add Plugin is idempotent for an existing entry')
print('DONE\t' .. count)
